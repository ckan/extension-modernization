#!/usr/bin/env python3
"""Check the distributable guidance without installing plugins or calling a model."""

from __future__ import annotations

import ast
import json
import os
import re
import subprocess
import sys
import tempfile
import textwrap
import tomllib
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urlsplit

import markdown
import yaml

CHECKLIST = ".agents/skills/ckan-review/references/checklist.md"
ROVO_RULES = ".rovodev/.review-agent.md"
DOCS_URL = "https://extension-modernization.readthedocs.io/en/latest/"
ROVO_HEADER = ("<!-- Generated by `make rovo` in ckan/extension-modernization from its "
               "review checklist. Projects may append their own rules below. -->\n\n")
DOC_LINK = re.compile(r"\]\((?:\.\./)+docs/([^)#]+)\.md(#[^)]*)?\)")
HOOKS = "hooks/hooks.json"
SESSION_HOOK = "hooks/session-start.sh"
GUARD_HOOK = "hooks/git-guard.sh"
EXPECTED_HOOKS = {
    "SessionStart": [{"hooks": [{"type": "command", "timeout": 10,
                                 "command": 'sh "${CLAUDE_PLUGIN_ROOT}/hooks/session-start.sh"'}]}],
    "PreToolUse": [{"matcher": "Bash",
                    "hooks": [{"type": "command", "timeout": 10,
                               "command": 'sh "${CLAUDE_PLUGIN_ROOT}/hooks/git-guard.sh"'}]}],
}
GUARD_PASSES = ["git status", "git -C src log --oneline -5", "git --no-pager diff --cached",
                "git branch --show-current", "git stash list", "git config --get user.name",
                "cd src && git status | head", "echo git push", "rg 'git push' docs",
                'cd "$(git rev-parse --show-toplevel)"', "git branch 2>/dev/null",
                "git branch --format '%(refname:short)'", "git branch -vv --contains HEAD",
                "if git diff --quiet; then echo clean; fi"]
GUARD_HOLDS = ["git commit -m 'x; y'", "git -C src push origin main", "git status && git add .",
               "git status\ngit checkout -- .", "bash -lc 'git push --force'", "FOO=1 git push",
               "/usr/bin/git clean -fd", "git branch -D old", "git stash", "git config user.name x",
               "sudo -u ckan git pull", "git st", "echo $(git reset --hard)",
               "git status # check\ngit push", "git fetch", "git branch -uorigin/main",
               "if git diff --quiet; then git commit -m x; fi",
               'for f in a b; do git add "$f"; done', "{ git push; }", "! git push",
               "git status || { git stash; }"]


def render_rovo_rules(root: Path) -> str:
    """Render the review checklist as Rovo Dev rules linking to the published docs."""
    def published(match: re.Match[str]) -> str:
        page = match[1]
        page = page[:-len("index")] if page == "index" or page.endswith("/index") else f"{page}/"
        return f"]({DOCS_URL}{page}{match[2] or ''})"

    return ROVO_HEADER + DOC_LINK.sub(published, (root / CHECKLIST).read_text())


def has_relative_links(rules: str) -> bool:
    """Return whether rendered Rovo rules still point into this repository."""
    return bool(re.search(r"\]\((?!https?://)", rules)) or "../" in rules


class Links(HTMLParser):
    def __init__(self, html: str) -> None:
        super().__init__()
        self.targets: list[str] = []
        self.ids: set[str] = set()
        self.feed(html)

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        values = dict(attrs)
        if values.get("id"):
            self.ids.add(values["id"])
        target = values.get("href" if tag == "a" else "src" if tag == "img" else "")
        if target:
            self.targets.append(target)


def run_hook(root: Path, script: str, project: str, *entries: str, from_cwd: bool = False,
             codex: bool = False, stdin: str = "") -> str | None:
    """Run a hook script in a temporary project; return its output, or None if it fails.

    Entries ending in ".py" are created as files, others as directories. With
    from_cwd, the project is found from the working directory, as in Codex.
    With codex, the hook also sees Codex's PLUGIN_ROOT variable.
    """
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp, project)
        path.mkdir()
        for entry in entries:
            target = path / entry
            if entry.endswith(".py"):
                target.parent.mkdir(parents=True, exist_ok=True)
                target.touch()
            else:
                target.mkdir(parents=True)
        env = {key: value for key, value in os.environ.items()
               if key not in ("CLAUDE_PROJECT_DIR", "PLUGIN_ROOT")}
        if not from_cwd:
            env["CLAUDE_PROJECT_DIR"] = str(path)
        if codex:
            env["PLUGIN_ROOT"] = str(root)
        try:
            result = subprocess.run(["sh", str(root / script)], cwd=path, env=env, input=stdin,
                                    capture_output=True, text=True, timeout=20)
        except subprocess.TimeoutExpired:
            return None
        return result.stdout.strip() if result.returncode == 0 else None


def guard_decision(root: Path, command: str, project: str = "ckanext-demo",
                   from_cwd: bool = False, codex: bool = False) -> str | None:
    """Return the git guard's decision: "" when the command passes, None if the hook fails."""
    payload = json.dumps({"tool_name": "Bash", "tool_input": {"command": command}})
    output = run_hook(root, GUARD_HOOK, project, from_cwd=from_cwd, codex=codex, stdin=payload)
    return json.loads(output)["hookSpecificOutput"]["permissionDecision"] if output else output


def check(root: Path) -> list[str]:
    errors: list[str] = []

    def require(condition: bool, message: str) -> None:
        if not condition:
            errors.append(message)

    manifests = [json.loads((root / provider / "plugin.json").read_text())
                 for provider in (".codex-plugin", ".claude-plugin")]
    codex, claude = manifests
    require(codex["name"] == claude["name"] == "extension-modernization",
            "Plugin names must match extension-modernization")
    require(codex["version"] == claude["version"], "Plugin versions disagree")
    require(bool(re.fullmatch(r"\d+\.\d+\.\d+", codex["version"])),
            "Use a release version in major.minor.patch form")
    for manifest in manifests:
        require(manifest.get("skills") == "./.agents/skills/",
                "Both clients must use the shared .agents/skills directory")
        require(not any(key in manifest for key in ("hooks", "mcpServers", "apps")),
                f"Declare hooks only in {HOOKS}; this plugin installs no services")

    hook_config = json.loads((root / HOOKS).read_text())
    require(isinstance(hook_config, dict) and set(hook_config) <= {"description", "hooks"}
            and hook_config.get("hooks") == EXPECTED_HOOKS,
            f"{HOOKS}: only the session reminder and the git guard may run")
    reminders = [run_hook(root, SESSION_HOOK, "ckanext-demo"),
                 run_hook(root, SESSION_HOOK, "plain", "ckanext"),
                 run_hook(root, SESSION_HOOK, "docker", "src/ckanext-x"),
                 run_hook(root, SESSION_HOOK, "docker", "src/ckanext-x", from_cwd=True),
                 run_hook(root, SESSION_HOOK, "core", "ckanext", "ckan/__init__.py"),
                 run_hook(root, SESSION_HOOK, "core", "ckan/__init__.py", "src/ckanext-x"),
                 run_hook(root, SESSION_HOOK, "other")]
    require([None if output is None else bool(output) for output in reminders]
            == [True, True, True, True, False, False, False],
            f"{SESSION_HOOK}: remind only in CKAN extension projects")
    for command in GUARD_PASSES:
        require(guard_decision(root, command) == "", f"{GUARD_HOOK}: should pass {command!r}")
    for command in GUARD_HOLDS:
        require(guard_decision(root, command) == "ask", f"{GUARD_HOOK}: should hold {command!r}")
    require(guard_decision(root, "git push", from_cwd=True, codex=True) == "deny"
            and guard_decision(root, "git push", codex=True) == "deny"
            and guard_decision(root, "git push", from_cwd=True) == "deny",
            f"{GUARD_HOOK}: deny in Codex, which cannot ask, and when the client is unknown")
    require(guard_decision(root, "git push", project="other") == "",
            f"{GUARD_HOOK}: pass everything outside CKAN extension projects")
    require(run_hook(root, GUARD_HOOK, "ckanext-demo", stdin='{"tool_input": "git push"}') == "",
            f"{GUARD_HOOK}: ignore malformed input without failing")

    for provider in (".agents/plugins", ".claude-plugin"):
        catalog = json.loads((root / provider / "marketplace.json").read_text())
        require(catalog["name"] == "ckan-guidelines", f"{provider}: wrong marketplace name")
        require(len(catalog["plugins"]) == 1, f"{provider}: expected one shared plugin")
        entry = catalog["plugins"][0]
        require(entry["name"] == codex["name"], f"{provider}: wrong plugin name")
        source = entry["source"]
        require(source == {"source": "local", "path": "./"} if isinstance(source, dict)
                else source == "./", f"{provider}: package the repository root")

    expected = {"ckan-development", "ckan-plan", "ckan-actions-auth", "ckan-database-models",
                "ckan-docker-dev", "ckan-frontend", "ckan-testing", "ckan-review"}
    skills = list((root / ".agents/skills").glob("*/SKILL.md"))
    require({path.parent.name for path in skills} == expected, "Expected all eight public skills")
    for path in skills:
        content = path.read_text()
        match = re.match(r"\A---\n(.*?)\n---(?:\n|$)", content, re.S)
        if not match:
            errors.append(f"{path.relative_to(root)}: missing YAML frontmatter")
            continue
        metadata = yaml.safe_load(match[1])
        require(isinstance(metadata, dict), f"{path}: frontmatter must be a mapping")
        if not isinstance(metadata, dict):
            continue
        require(metadata.get("name") == path.parent.name, f"{path}: skill name mismatch")
        description = metadata.get("description", "")
        require(isinstance(description, str) and 0 < len(description) <= 1024,
                f"{path}: provide a concise trigger description")
        require(not metadata.get("disable-model-invocation"), f"{path}: allow automatic selection")

    paths = [root / name for name in ("README.md", "AGENTS.md", "CLAUDE.md")]
    for directory in ("docs", ".agents/skills", "agents"):
        paths.extend((root / directory).rglob("*.md"))
    parsed: dict[Path, Links] = {}
    snippets = 0
    for path in paths:
        source = path.read_text()
        frontmatter = re.match(r"\A---\n.*?\n---\n", source, re.S)
        offset = frontmatter[0].count("\n") if frontmatter else 0
        body = source[frontmatter.end():] if frontmatter else source
        parsed[path.resolve()] = Links(markdown.markdown(
            body, extensions=["toc", "attr_list", "tables", "pymdownx.superfences"]))
        fence: tuple[str, str, int] | None = None
        lines: list[str] = []
        for number, line in enumerate(body.splitlines(), 1):
            marker = re.match(r"^\s*(`{3,}|~{3,})(.*)$", line)
            if fence is None and marker:
                language = marker[2].strip().split(" ", 1)[0]
                fence = (marker[1], language, number)
                lines = []
            elif fence and marker and not marker[2].strip() and marker[1][0] == fence[0][0] and len(marker[1]) >= len(fence[0]):
                if fence[1] in ("python", "py"):
                    snippets += 1
                    try:
                        ast.parse(textwrap.dedent("\n".join(lines)))
                    except SyntaxError as exc:
                        errors.append(f"{path.relative_to(root)}:{offset + fence[2] + (exc.lineno or 1)}: {exc.msg}")
                fence = None
            elif fence:
                lines.append(line)
        require(fence is None, f"{path.relative_to(root)}: unclosed code fence")

    for path, links in parsed.items():
        for target in links.targets:
            url = urlsplit(target)
            if url.scheme == "file":
                errors.append(f"{path.relative_to(root)}: nonportable file URL {target}")
                continue
            if url.scheme or url.netloc:
                continue
            destination = (path.parent / unquote(url.path)).resolve() if url.path else path
            if not destination.is_relative_to(root):
                errors.append(f"{path.relative_to(root)}: reference escapes package: {target}")
            elif not destination.exists():
                errors.append(f"{path.relative_to(root)}: missing reference: {target}")
            elif url.fragment and destination in parsed:
                require(unquote(url.fragment) in parsed[destination].ids,
                        f"{path.relative_to(root)}: missing heading: {target}")

    config = tomllib.loads((root / "zensical.toml").read_text())

    def nav_pages(value: object) -> set[str]:
        if isinstance(value, str):
            return {value}
        if isinstance(value, dict):
            return set().union(*(nav_pages(item) for item in value.values()))
        if isinstance(value, list):
            return set().union(*(nav_pages(item) for item in value))
        return set()

    rovo_rules = render_rovo_rules(root)
    require(not has_relative_links(rovo_rules),
            f"{CHECKLIST}: Rovo rules can only link to pages under docs/")
    require((root / ROVO_RULES).is_file() and (root / ROVO_RULES).read_text() == rovo_rules,
            f"{ROVO_RULES} is out of date with {CHECKLIST}; run make rovo")

    actual_docs = {str(path.relative_to(root / "docs")) for path in (root / "docs").rglob("*.md")}
    require(nav_pages(config["project"]["nav"]) == actual_docs,
            "Documentation navigation must cover exactly the existing guide pages")
    print(f"Checked {len(skills)} skills, {len(parsed)} Markdown files, and {snippets} Python snippets.")
    return errors


if __name__ == "__main__":
    write_rovo = "--write-rovo" in sys.argv[1:]
    roots = [arg for arg in sys.argv[1:] if arg != "--write-rovo"]
    package_root = Path(roots[0]).resolve() if roots else Path(__file__).resolve().parents[1]
    try:
        if write_rovo:
            rules = render_rovo_rules(package_root)
            if has_relative_links(rules):
                raise SystemExit(f"{CHECKLIST}: Rovo rules can only link to pages under docs/")
            (package_root / ROVO_RULES).parent.mkdir(exist_ok=True)
            (package_root / ROVO_RULES).write_text(rules)
            print(f"Wrote {ROVO_RULES}")
        failures = check(package_root)
    except (OSError, ValueError, KeyError, yaml.YAMLError) as exc:
        raise SystemExit(f"Invalid package: {exc}") from exc
    if failures:
        raise SystemExit("\n".join(failures))
    print("Plugin metadata, bundled references, and snippet syntax passed.")
